import assert from 'node:assert/strict';
import { suggestDraft } from '../src/lib/reports/draft.ts';
const locations=[];
for(const tower of [1,2])for(const code of ['corridor','elevators','parking','parking_gate','entrance'])locations.push({id:`${tower}-${code}`,code,name:code,building_id:`tower-${tower}`,buildings:{name:`Tower ${tower}`}});
for(const code of ['playground','pool','rear_gate','waste'])locations.push({id:code,code,name:code,building_id:null,buildings:null});
let d=suggestDraft('Во второй башне на третьем этаже тараканы в коридоре',locations);
assert.equal(d.place?.id,'2-corridor');
assert.equal(d.category,'pest_control');assert.equal(d.detail,'Floor 3');
d=suggestDraft('Cockroaches in Tower 2 corridor on floor 3',locations);
assert.equal(d.place?.id,'2-corridor');assert.equal(d.detail,'Floor 3');
d=suggestDraft('Tower 1 elevator #2 does not work',locations);
assert.equal(d.place?.id,'1-elevators');assert.equal(d.detail,'Elevator #2');
assert.equal(suggestDraft('Не работает лифт',locations).place,undefined);
assert.equal(suggestDraft('Tower 1 and Tower 2 elevators broken',locations).place,undefined);
assert.equal(suggestDraft('Сломаны качели на детской площадке',locations).place?.id,'playground');
assert.equal(suggestDraft('Просим открыть задние ворота',locations).requestKind,'change_request');
assert.equal(suggestDraft('Tower 2 parking gate is stuck',locations).place?.id,'2-parking_gate');
assert.equal(suggestDraft('Мне нужна помощь',locations).category,'other');
console.log('Draft suggestions: 12 assertions passed.');
